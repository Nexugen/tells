/**
 * Writes bench/EVAL.md from fp-v0.2.json, fp-now.json and eval.json, and compares the rule
 * verdict of an older copy of the code on the same held-out split.
 *
 *   node --experimental-strip-types bench/eval-report.ts [path/to/old/src]
 */
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { lint as lintNow } from '../src/lint.ts';
import type { Register } from '../src/types.ts';

const here = dirname(fileURLToPath(import.meta.url));
const read = (f: string) => JSON.parse(readFileSync(join(here, f), 'utf8'));
const before = read('fp-v0.2.json');
const now = read('fp-now.json');
const ev = read('eval.json');
const REGS = ['casual', 'professional', 'technical', 'marketing'] as const;
const pct = (x: number | undefined) => (x === undefined ? '0%' : `${Math.round(x * 100)}%`);

// Same held-out split as eval.ts.
const heldOut = (key: string) => parseInt(createHash('sha256').update(key).digest('hex').slice(0, 8), 16) % 10 < 3;
type Row = { register: Register; text: string; ai: boolean };
const rows: Row[] = (read('human.json').samples as { id: string; register: Register; text: string }[]).filter((h) => heldOut(`h:${h.id}`)).map((h) => ({ ...h, ai: false }));
for (const f of readdirSync(join(here, 'out')).filter((f) => f.endsWith('.json') && !f.includes('+'))) {
  for (const it of read(join('out', f)).items) if (heldOut(`p:${it.id}`)) rows.push({ register: it.register, text: it.text, ai: true });
}
const verdict = (lint: typeof lintNow) => {
  const flag = (r: Row) => lint(r.text, { register: r.register }).findings.some((f) => f.severity !== 'info');
  const h = rows.filter((r) => !r.ai), m = rows.filter((r) => r.ai);
  const fh = h.filter(flag).length, fm = m.filter(flag).length;
  return { left: 1 - fh / h.length, flagged: fm / m.length, precision: fm / Math.max(1, fm + fh), h: h.length, m: m.length };
};
const oldSrc = process.argv[2] ? resolve(process.argv[2]) : undefined;
const vOld = oldSrc ? verdict(((await import(join(oldSrc, 'lint.ts'))) as typeof import('../src/lint.ts')).lint) : undefined;
const vNow = verdict(lintNow);

const ruleIds = [...new Set([...Object.keys(before.rules), ...Object.keys(now.rules)])];
const worst = (r: Record<string, { blocking: number }> | undefined) => Math.max(0, ...Object.values(r ?? {}).map((v) => v.blocking));
ruleIds.sort((a, b) => worst(before.rules[b]) - worst(before.rules[a]) || a.localeCompare(b));
const changed = ruleIds.filter((id) => REGS.some((g) => (before.rules[id]?.[g]?.blocking ?? 0) > 0 || (now.rules[id]?.[g]?.blocking ?? 0) > 0));

const md = `# Accuracy

Generated by \`bench/eval-report.ts\` from \`fp-v0.2.json\`, \`fp-now.json\` and \`eval.json\`. A text counts as **flagged** when tells reports at least one warning or error. Hints (info) never flag a text.

## Human writing left alone

Share of human samples with no warning and no error, checked against the register they were written in. All ${Object.values(now.samples as Record<string, number>).reduce((a, b) => a + b, 0)} samples in \`human.json\`, held-out ones included.

| Register | Samples | v0.2 | Now |
| --- | ---: | ---: | ---: |
${REGS.map((g) => `| ${g} | ${now.samples[g]} | ${pct(1 - before.anyBlocking[g])} | ${pct(1 - now.anyBlocking[g])} |`).join('\n')}

These samples were used to tune the rules, so they flatter the result. Two more sets were fetched from other Stack Exchange sites to check that:

| Set | Register | Samples | Rules leave alone |
| --- | --- | ---: | ---: |
${(['freshHuman', 'finalHuman'] as const).flatMap((k) => REGS.filter((g) => ev[k]?.[g]).map((g) => `| ${k === 'freshHuman' ? 'second' : 'final'} | ${g} | ${ev[k][g].samples} | ${pct(ev[k][g].rulesLeftAlone)} |`)).join('\n')}

The second set was fetched after the first round of changes. Its misfires (dashes, filler transitions, short questions) led to a second round, so it is no longer untouched. The final set was fetched after that and measured once: the rules left alone 98% of its casual samples and 77% of its professional ones. Those professional misfires were "magical" in a fiction-writing answer, "harness" as a noun, "insane" and a legal "[company's]" substitution. They were fixed, which gives the numbers above, and the final set is now spent too. Expect real-world professional writing to land somewhere between those two figures.

## Telling model output apart

Held-out split: ${ev.split.test.human} human and ${ev.split.test.ai} model texts (Haiku, Sonnet and Opus answering ${read('prompts.json').prompts.length} everyday prompts, split by prompt).

| Verdict | Human left alone | Model output flagged | Precision |
| --- | ---: | ---: | ---: |
${vOld ? `| Rules, v0.2 | ${pct(vOld.left)} | ${pct(vOld.flagged)} | ${pct(vOld.precision)} |\n` : ''}| Rules, now | ${pct(vNow.left)} | ${pct(vNow.flagged)} | ${pct(vNow.precision)} |
| Style layer (experiment) | ${pct(ev.heldOut.style.humanLeftAlone)} | ${pct(ev.heldOut.style.aiFlagged)} | ${pct(ev.heldOut.style.precision)} |
| Rules or style | ${pct(ev.heldOut.both.humanLeftAlone)} | ${pct(ev.heldOut.both.aiFlagged)} | ${pct(ev.heldOut.both.precision)} |

By register, rules now:

| Register | Human left alone | Model output flagged |
| --- | ---: | ---: |
${REGS.map((g) => `| ${g} | ${pct(ev.heldOutByRegister.rules[g].humanLeftAlone)} (${ev.heldOutByRegister.rules[g].human}) | ${pct(ev.heldOutByRegister.rules[g].aiFlagged)} (${ev.heldOutByRegister.rules[g].ai}) |`).join('\n')}

Most model output that passes is short casual text. A current model asked for a text to a friend writes something close to what a person would, and no rule should claim otherwise. Technical answers from models carry almost no known tells either.

## The style layer, and why it is not shipped

\`bench/style.ts\` measures function words, punctuation, rhythm and layout, and \`eval.ts\` trains a logistic regression on them. On the held-out split it reaches an AUC of ${ev.heldOut.style.auc} and flags more model output than the rules do. It also scores a plain check-in text that a user reported ("Hey, how have you been? ...") at 0.94, well over its threshold. The human samples are forum posts and the model samples are answers to prompts, so the layer learns where a text came from as much as who wrote it. It stays in \`bench/\` as an experiment and nothing in the package uses it.

## Human signals

Lift is the share of human training texts with the signal divided by the share of model ones (1 means no difference).

| Signal | Human | Model | Lift |
| --- | ---: | ---: | ---: |
${ev.signalLift.map((s: { id: string; human: number; model: number; lift: number }) => `| \`${s.id}\` | ${pct(s.human)} | ${pct(s.model)} | ${s.lift} |`).join('\n')}

Only an opinion with a stake and asides show a real lift. Models now use numbers, names, dates, contractions and plain verbs as often as people, or more, because the prompts hand them the facts. That is why the signal score is gone. Lint still lists which signals a text has, and only calls one missing when the register's profile shows a clear gap.

## False positives per rule

Share of human samples where the rule raised a warning or an error, before (v0.2) and now. Rules that never did in either version are left out.

| Rule | ${REGS.map((g) => `${g} v0.2 | now`).join(' | ')} |
| --- | ${REGS.map(() => '---: | ---:').join(' | ')} |
${changed.map((id) => `| \`${id}\` | ${REGS.map((g) => `${pct(before.rules[id]?.[g]?.blocking)} | ${pct(now.rules[id]?.[g]?.blocking)}`).join(' | ')} |`).join('\n')}
`;
writeFileSync(join(here, 'EVAL.md'), md);
console.log(md);
